function sizeClass(cls: string): number {
  if (cls.includes('text-4xl')) return 36;
  if (cls.includes('text-2xl')) return 24;
  if (cls.includes('text-xl')) return 20;
  if (cls.includes('text-lg')) return 18;
  if (cls.includes('text-sm')) return 14;
  if (cls.includes('text-xs')) return 12;
  return 16;
}

const Icon = memo(function Icon({ name, className = '' }: { name: string; className?: string }) {
  const Comp = MAP[name];
  if (!Comp) {
    console.warn(`[Icon] 未注册的图标: "${name}"`);
    return <span className={className}>?</span>;
  }
  return <Comp className={className} size={sizeClass(className)} />;
});

export default Icon;
